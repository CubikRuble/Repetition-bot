package org.example.storage;

import java.util.List;
import org.example.catalog.Movie;

/**
 * Хранилище списков «посмотреть позже». У каждого пользователя свой список фильмов,
 * а фильм в списке однозначно определяется идентификатором Кинопоиска. Интерфейс ничего не знает
 * ни о логике диалога, ни о Telegram, поэтому реализацию (память, файл, база данных)
 * можно заменить, не трогая остальной код.
 */
public interface WatchlistStorage {

    /**
     * Возвращает все фильмы пользователя в порядке добавления.
     * @param userId идентификатор пользователя
     * @return неизменяемая копия списка; пустой список, если у пользователя ещё нет фильмов
     */
    List<Movie> getAll(long userId);

    /**
     * Добавляет фильм в конец списка пользователя, если фильма с таким идентификатором там ещё нет.
     * @param userId идентификатор пользователя
     * @param movie фильм, который сохраняется целиком
     * @return {@code true}, если фильм добавлен; {@code false}, если он уже был в списке
     */
    boolean add(long userId, Movie movie);

    /**
     * Удаляет из списка пользователя фильм с указанным идентификатором Кинопоиска.
     * @param userId идентификатор пользователя
     * @param movieId идентификатор фильма на Кинопоиске
     * @return {@code true}, если фильм был найден и удалён
     */
    boolean remove(long userId, long movieId);
}
