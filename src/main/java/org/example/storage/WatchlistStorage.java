package org.example.storage;

import java.util.List;
import org.example.catalog.Movie;

/**
 * Хранилище списков «посмотреть позже». У каждого пользователя свой список фильмов,
 * а фильм в списке однозначно определяется идентификатором Кинопоиска. Вместе с фильмом хранится
 * оценка пользователя: она переживает перезапуск бота, если реализация хранит данные на диске.
 * Интерфейс ничего не знает ни о логике диалога, ни о Telegram, поэтому реализацию
 * (память, файл, база данных) можно заменить, не трогая остальной код.
 */
public interface WatchlistStorage {

    /**
     * Возвращает все записи списка пользователя в порядке добавления.
     * @param userId идентификатор пользователя
     * @return неизменяемая копия списка; пустой список, если у пользователя ещё нет фильмов
     */
    List<WatchlistEntry> getAll(long userId);

    /**
     * Добавляет фильм без оценки в конец списка пользователя, если фильма с таким идентификатором
     * там ещё нет. Если фильм уже в списке, его оценка не меняется.
     * @param userId идентификатор пользователя
     * @param movie фильм, который сохраняется целиком
     * @return {@code true}, если фильм добавлен; {@code false}, если он уже был в списке
     */
    boolean add(long userId, Movie movie);

    /**
     * Сохраняет оценку фильма из списка пользователя; прежняя оценка заменяется. Допустимость
     * значения проверяет вызывающий код: хранилище записывает то, что ему передали.
     * @param userId идентификатор пользователя
     * @param movieId идентификатор фильма на Кинопоиске
     * @param rating оценка пользователя от 1 до 10
     * @return {@code true}, если фильм был в списке и оценка сохранена; {@code false}, если такого
     *         фильма в списке нет
     */
    boolean rate(long userId, long movieId, int rating);

    /**
     * Удаляет из списка пользователя фильм с указанным идентификатором Кинопоиска.
     * @param userId идентификатор пользователя
     * @param movieId идентификатор фильма на Кинопоиске
     * @return {@code true}, если фильм был найден и удалён
     */
    boolean remove(long userId, long movieId);
}
